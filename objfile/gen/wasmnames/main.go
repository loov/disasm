// Command wasmnames builds the wasm mnemonic tables for package objfile
// from the instruction catalog of github.com/eliben/watgo, which keeps
// it in an internal package. It reads the module's source from the
// module cache, so run it after updating watgo:
//
//	go generate ./objfile
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// registration matches one catalog entry: the registering function,
// the kind constant, and the mnemonic.
var registration = regexp.MustCompile(`\b(\w+)\((Instr[A-Za-z0-9]+), "([^"]+)"`)

func main() {
	out := flag.String("out", "wasm_names_gen.go", "output file")
	flag.Parse()

	dir, version := module("github.com/eliben/watgo")
	src, err := os.ReadFile(filepath.Join(dir, "internal", "instrdef", "instruction_defs.go"))
	if err != nil {
		log.Fatal(err)
	}

	names := map[string]string{}
	var mem, plain []string
	for _, m := range registration.FindAllStringSubmatch(string(src), -1) {
		fn, kind, name := m[1], m[2], m[3]
		if _, dup := names[kind]; dup {
			continue
		}
		names[kind] = name
		switch fn {
		case "memoryInstr":
			mem = append(mem, kind)
		case "directOp", "prefixedOp":
			plain = append(plain, kind)
		}
	}
	if len(names) == 0 {
		log.Fatal("no instruction registrations found; has the catalog format changed?")
	}
	kinds := make([]string, 0, len(names))
	for k := range names {
		kinds = append(kinds, k)
	}
	slices.Sort(kinds)
	slices.Sort(mem)
	slices.Sort(plain)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./gen/wasmnames from github.com/eliben/watgo %s; DO NOT EDIT.\n", version)
	fmt.Fprintf(&b, "// The catalog is public domain (Unlicense); see the watgo LICENSE.\n\n")
	fmt.Fprintf(&b, "package objfile\n\nimport \"github.com/eliben/watgo/wasmir\"\n\n")
	fmt.Fprintf(&b, "// wasmOpNames maps instruction kinds to their WAT mnemonics.\n")
	fmt.Fprintf(&b, "var wasmOpNames = map[wasmir.InstrKind]string{\n")
	for _, k := range kinds {
		fmt.Fprintf(&b, "\twasmir.%s: %q,\n", k, names[k])
	}
	fmt.Fprintf(&b, "}\n\n")
	set(&b, "wasmMemOps", "wasmMemOps are the instructions printed with offset= and align= immediates.", mem)
	fmt.Fprintf(&b, "\n")
	set(&b, "wasmPlainOps", "wasmPlainOps are the instructions without immediates.", plain)

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// set writes a map[InstrKind]bool literal.
func set(b *bytes.Buffer, name, doc string, kinds []string) {
	fmt.Fprintf(b, "// %s\nvar %s = map[wasmir.InstrKind]bool{\n", doc, name)
	for _, k := range kinds {
		fmt.Fprintf(b, "\twasmir.%s: true,\n", k)
	}
	fmt.Fprintf(b, "}\n")
}

// module returns the source directory and version of a dependency.
func module(path string) (dir, version string) {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", path).Output()
	if err != nil {
		log.Fatalf("locating %s: %v", path, err)
	}
	dir, version, _ = strings.Cut(strings.TrimSpace(string(out)), " ")
	return dir, version
}
